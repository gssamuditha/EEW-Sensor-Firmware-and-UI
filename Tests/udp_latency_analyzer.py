"""
udp_latency_analyzer.py - Scientific-Grade EEW UDP Latency Evaluation Tool
===========================================================================
Receives EEW sensor UDP packets and computes end-to-end One-Way Delay (OWD)
from packet sample-origin timestamp to OS receive time.

Usage
-----
  python udp_latency_analyzer.py               # Live capture, Ctrl+C to stop
  python udp_latency_analyzer.py --duration 300  # Fixed 300-second run
  python udp_latency_analyzer.py --selftest      # Loopback self-test
  python udp_latency_analyzer.py --no-dashboard  # Plain stdout mode

Requirements
------------
  pip install numpy matplotlib scipy
  On Windows for the dashboard: pip install windows-curses

Methodology
-----------
  OWD = t_recv(PC) - packet_timestamp(RPi)
  packet_timestamp is the NTP-disciplined UTC epoch of the FIRST sample
  in the packet, generated by the Software PLL in sensor.py.

  IMPORTANT: Both clocks must be NTP-synchronized.
    Windows: w32tm /query /status
    Linux:   chronyc tracking

Output files
------------
  udp_latency_data_<TIMESTAMP>.csv     - raw per-packet measurements
  udp_latency_report_<TIMESTAMP>.txt   - human-readable summary report
  udp_latency_<TIMESTAMP>_owd.png      - OWD time-series
  udp_latency_<TIMESTAMP>_hist.png     - OWD histogram + fitted PDF
  udp_latency_<TIMESTAMP>_cdf.png      - OWD empirical CDF
  udp_latency_<TIMESTAMP>_jitter.png   - Jitter time-series

Packet Format (EEW Datacast / Raspberry Shake compatible)
----------------------------------------------------------
  {'ENZ', <packet_timestamp>, <s1>, <s2>, ..., <s25>}
  or legacy Python list:
  ['ENZ', <packet_timestamp>, <s1>, <s2>, ..., <s25>]
"""

