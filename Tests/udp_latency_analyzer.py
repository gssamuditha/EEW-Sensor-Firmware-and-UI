# ── Plain stdout logger ───────────────────────────────────────────────────────

def run_plain_logger(records, stop_event, rx_queue, args, session_start, clock_offset_ms):
    rolling    = RollingStats(ROLLING_WINDOW_S)
    jitter_ema = 0.0
    n_received = 0
    n_loss     = 0
    last_ts    = {}
    seq        = 0
    last_print = 0.0

    print(f"{'SEQ':>6}  {'CH':5}  {'OWD_MS':>10}  {'JIT_MS':>9}  {'P50':>8}  {'P95':>8}  LOSS")

    while not stop_event.is_set():
        try:
            recv_utc, raw = rx_queue.get(timeout=0.2)
        except queue.Empty:
            continue
        parsed = parse_eew_packet(raw)
        if parsed is None:
            continue
        channel, packet_ts, samples = parsed
        owd_ms = (recv_utc - packet_ts) * 1000.0
        if channel in last_ts and rolling.values():
            delta = abs(owd_ms - rolling.values()[-1])
            jitter_ema += JITTER_ALPHA * (delta - jitter_ema)
        is_loss = False
        if channel in last_ts:
            gap = packet_ts - last_ts[channel]
            if gap > LOSS_THRESHOLD_S:
                n_loss += max(0, round(gap / EXPECTED_INTERVAL_S) - 1)
                is_loss = True
        last_ts[channel] = packet_ts
        n_received += 1
        rolling.add(recv_utc, owd_ms)
        records.append(PacketRecord(
            seq=seq, recv_utc=recv_utc, packet_ts=packet_ts, channel=channel,
            owd_ms=owd_ms, jitter_ms=jitter_ema, n_samples=len(samples),
            clock_offset_ms=clock_offset_ms, is_loss_gap=is_loss,
        ))
        seq += 1
        now = time.time()
        if now - last_print >= 1.0:
            s = rolling.compute()
            print(f"{seq:>6}  {channel:5}  {owd_ms:>10.2f}  {jitter_ema:>9.3f}  "
                  f"{s['p50']:>8.2f}  {s['p95']:>8.2f}  {'LOSS' if is_loss else ''}")
            last_print = now


# ── UDP receiver thread ───────────────────────────────────────────────────────

def udp_receiver(port, bind_ip, rx_queue, stop_event):
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    try:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 1 << 20)
    except OSError:
        pass
    sock.bind((bind_ip, port))
    sock.settimeout(0.2)
    print(f"[UDP] Bound to {bind_ip}:{port}")
    while not stop_event.is_set():
        try:
            raw, addr = sock.recvfrom(8192)
            recv_utc  = time.time()
            rx_queue.put_nowait((recv_utc, raw))
        except socket.timeout:
            continue
        except OSError:
            break
    sock.close()


