# ── Data structures ──────────────────────────────────────────────────────────

class PacketRecord:
    """One captured UDP packet full measurement record."""
    __slots__ = (
        'seq', 'recv_utc', 'packet_ts', 'channel',
        'owd_ms', 'jitter_ms', 'n_samples',
        'clock_offset_ms', 'is_loss_gap',
    )
    def __init__(self, seq, recv_utc, packet_ts, channel,
                 owd_ms, jitter_ms, n_samples, clock_offset_ms, is_loss_gap=False):
        self.seq             = seq
        self.recv_utc        = recv_utc
        self.packet_ts       = packet_ts
        self.channel         = channel
        self.owd_ms          = owd_ms
        self.jitter_ms       = jitter_ms
        self.n_samples       = n_samples
        self.clock_offset_ms = clock_offset_ms
        self.is_loss_gap     = is_loss_gap


class RollingStats:
    """O(1) rolling window statistics using a deque."""
    def __init__(self, window_s=ROLLING_WINDOW_S):
        self.window_s = window_s
        self._data    = collections.deque()

    def add(self, ts, value):
        self._data.append((ts, value))
        cutoff = ts - self.window_s
        while self._data and self._data[0][0] < cutoff:
            self._data.popleft()

    def values(self):
        return [v for _, v in self._data]

    def count(self):
        return len(self._data)

    def compute(self):
        vals = self.values()
        if not vals:
            return {'mean': 0.0, 'std': 0.0, 'min': 0.0,
                    'max': 0.0, 'p50': 0.0, 'p95': 0.0, 'p99': 0.0, 'n': 0}
        a = np.array(vals, dtype=np.float64)
        return {
            'mean': float(np.mean(a)),
            'std':  float(np.std(a, ddof=1)) if len(a) > 1 else 0.0,
            'min':  float(np.min(a)),
            'max':  float(np.max(a)),
            'p50':  float(np.percentile(a, 50)),
            'p95':  float(np.percentile(a, 95)),
            'p99':  float(np.percentile(a, 99)),
            'n':    len(a),
        }


# ── NTP clock utilities ──────────────────────────────────────────────────────

def get_ntp_offset_ms():
    """Return local clock offset from NTP in ms, or None on failure."""
    try:
        if sys.platform == 'win32':
            result = subprocess.run(
                ['w32tm', '/query', '/status'],
                capture_output=True, text=True, timeout=3
            )
            for line in result.stdout.splitlines():
                if 'Phase Offset' in line:
                    parts = line.split(':', 1)
                    if len(parts) > 1:
                        val_str = parts[1].strip().split('s')[0].strip()
                        try:
                            return float(val_str) * 1000.0
                        except ValueError:
                            pass
        else:
            result = subprocess.run(
                ['chronyc', 'tracking'],
                capture_output=True, text=True, timeout=3
            )
            for line in result.stdout.splitlines():
                if 'System time' in line:
                    parts = line.split(':', 1)
                    if len(parts) > 1:
                        val_parts = parts[1].strip().split()
                        if val_parts:
                            try:
                                val = float(val_parts[0]) * 1000.0
                                if 'slow' in parts[1]:
                                    val = -val
                                return val
                            except ValueError:
                                pass
    except Exception:
        pass
    return None


# ── Packet parser ────────────────────────────────────────────────────────────

def parse_eew_packet(raw):
    """Parse an EEW sensor UDP packet.

    Supports Raspberry Shake Datacast format:
      {'ENZ', 1722000000.123456, s1, s2, ..., s25}
    and legacy Python list format:
      ['ENZ', 1722000000.123456, s1, s2, ..., s25]

    Returns (channel, packet_ts, samples) or None on parse error.
    """
    try:
        decoded = raw.decode('utf-8', errors='replace').strip()
        normalized = decoded
        if normalized.startswith('{') and normalized.endswith('}'):
            normalized = '[' + normalized[1:-1] + ']'
        packet = ast.literal_eval(normalized)
        if not isinstance(packet, (list, tuple)) or len(packet) < 3:
            return None
        channel   = str(packet[0]).strip("' \"")
        packet_ts = float(packet[1])
        samples   = packet[2:]
        return channel, packet_ts, samples
    except Exception:
        return None


# ── Self-test sender ─────────────────────────────────────────────────────────

def _selftest_sender(port, stop_event):
    """Background thread: sends fake EEW packets to localhost for loopback testing."""
    sock      = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    interval  = EXPECTED_INTERVAL_S
    next_send = time.time() + 0.5
    seq       = 0
    print(f"[SELFTEST] Sending fake packets to 127.0.0.1:{port} every {interval*1000:.0f} ms")
    while not stop_event.is_set():
        now = time.time()
        remaining = next_send - now
        if remaining > 0:
            time.sleep(remaining)
        packet_ts   = next_send - interval
        samples     = [round(0.01 * math.sin(2 * math.pi * seq * 0.01), 6)] * 25
        samples_str = ', '.join(str(s) for s in samples)
        pkt         = "{'ENZ', " + f"{packet_ts:.6f}" + ", " + samples_str + "}"
        try:
            sock.sendto(pkt.encode('utf-8'), ('127.0.0.1', port))
        except OSError:
            pass
        next_send += interval
        seq += 1
    sock.close()


