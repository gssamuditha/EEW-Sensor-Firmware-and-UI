# ── Histogram bar ─────────────────────────────────────────────────────────────

def _build_histogram_bar(values, width=30, max_val=None):
    if not values:
        return ' ' * width, 0.0, 1.0
    a    = np.array(values, dtype=np.float64)
    vmin = np.min(a)
    vmax = max_val if max_val is not None else np.percentile(a, 99)
    if vmax <= vmin:
        vmax = vmin + 1.0
    bins = np.linspace(vmin, vmax, width + 1)
    counts, _ = np.histogram(a, bins=bins)
    bar_max = max(counts.max(), 1)
    chars = ' \u2581\u2582\u2583\u2584\u2585\u2586\u2587\u2588'
    bar_str = ''.join(chars[min(int(c / bar_max * 8), 8)] for c in counts)
    return bar_str, vmin, vmax


# ── Curses dashboard ──────────────────────────────────────────────────────────

def run_dashboard(stdscr, records, stop_event, rx_queue, args, session_start, clock_offset_ms):
    import curses
    curses.curs_set(0)
    curses.start_color()
    curses.use_default_colors()
    curses.init_pair(1, curses.COLOR_CYAN,   -1)
    curses.init_pair(2, curses.COLOR_GREEN,  -1)
    curses.init_pair(3, curses.COLOR_YELLOW, -1)
    curses.init_pair(4, curses.COLOR_RED,    -1)
    curses.init_pair(5, curses.COLOR_WHITE,  -1)
    curses.init_pair(6, curses.COLOR_MAGENTA,-1)

    C_TITLE = curses.color_pair(1) | curses.A_BOLD
    C_GOOD  = curses.color_pair(2)
    C_WARN  = curses.color_pair(3)
    C_ERR   = curses.color_pair(4)
    C_LABEL = curses.color_pair(5)
    C_HIST  = curses.color_pair(6)

    rolling      = RollingStats(ROLLING_WINDOW_S)
    jitter_ema   = 0.0
    n_received   = 0
    n_loss       = 0
    last_ts      = {}
    seq          = 0

    stdscr.nodelay(True)

    while not stop_event.is_set():
        # Drain queue
        while True:
            try:
                recv_utc, raw = rx_queue.get_nowait()
            except queue.Empty:
                break
            parsed = parse_eew_packet(raw)
            if parsed is None:
                continue
            channel, packet_ts, samples = parsed
            owd_ms = (recv_utc - packet_ts) * 1000.0
            if channel in last_ts and rolling.values():
                delta = abs(owd_ms - rolling.values()[-1])
                jitter_ema += JITTER_ALPHA * (delta - jitter_ema)
            is_loss = False
            if channel in last_ts:
                gap = packet_ts - last_ts[channel]
                if gap > LOSS_THRESHOLD_S:
                    n_loss += max(0, round(gap / EXPECTED_INTERVAL_S) - 1)
                    is_loss = True
            last_ts[channel] = packet_ts
            n_received += 1
            rolling.add(recv_utc, owd_ms)
            records.append(PacketRecord(
                seq=seq, recv_utc=recv_utc, packet_ts=packet_ts, channel=channel,
                owd_ms=owd_ms, jitter_ms=jitter_ema, n_samples=len(samples),
                clock_offset_ms=clock_offset_ms, is_loss_gap=is_loss,
            ))
            seq += 1

        # Draw
        stdscr.erase()
