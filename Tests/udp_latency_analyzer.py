    class RecordList(list):
        def __init__(self):
            super().__init__()
            self._csv_q = None
        def append(self, record):
            super().append(record)
            if self._csv_q is not None:
                try:
                    self._csv_q.put_nowait(record)
                except queue.Full:
                    pass

    records        = RecordList()
    rx_queue       = queue.Queue(maxsize=2000)
    stop_event     = threading.Event()
    session_start  = time.time()

