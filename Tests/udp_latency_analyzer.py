def open_csv(filepath):
    fh     = open(filepath, 'w', newline='', buffering=1, encoding='utf-8')
    writer = csv.DictWriter(fh, fieldnames=CSV_FIELDNAMES)
    writer.writeheader()
    return fh, writer

def write_csv_row(writer, r):
    writer.writerow({
        'seq':              r.seq,
        'recv_utc':         f"{r.recv_utc:.6f}",
        'packet_ts':        f"{r.packet_ts:.6f}",
        'channel':          r.channel,
        'owd_ms':           f"{r.owd_ms:.3f}",
        'jitter_ms':        f"{r.jitter_ms:.3f}",
        'n_samples':        r.n_samples,
        'clock_offset_ms':  f"{r.clock_offset_ms:.3f}" if r.clock_offset_ms is not None else 'N/A',
        'is_loss_gap':      1 if r.is_loss_gap else 0,
    })


# ── Report generator ─────────────────────────────────────────────────────────

def generate_text_report(records, session_start, session_end, filepath, args):
    """Write a human-readable scientific text report."""
    owd_vals   = np.array([r.owd_ms for r in records if not r.is_loss_gap], dtype=np.float64)
    n_total    = len(records)
    n_loss     = sum(1 for r in records if r.is_loss_gap)
    n_received = n_total - n_loss
    duration   = session_end - session_start
    loss_rate  = (n_loss / n_total * 100) if n_total > 0 else 0.0

    with open(filepath, 'w', encoding='utf-8') as f:
        def w(line=''):
            f.write(line + '\n')

        w("=" * 72)
        w("  EEW UDP LATENCY EVALUATION -- SCIENTIFIC REPORT")
        w("=" * 72)
        w(f"  Generated : {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}")
        w(f"  Station   : {args.ip}:{args.port}")
        w(f"  Duration  : {duration:.1f} s  ({duration/60:.2f} min)")
        w(f"  Mode      : {'SELFTEST (loopback)' if args.selftest else 'LIVE capture'}")
        w()
        w("-" * 72)
        w("  PACKET STATISTICS")
        w("-" * 72)
        w(f"  Total packets logged      : {n_total}")
        w(f"  Packets received          : {n_received}")
        w(f"  Packets lost (gap events) : {n_loss}")
        w(f"  Packet loss rate          : {loss_rate:.4f} %")
        w()

        if len(owd_vals) >= 2:
            w("-" * 72)
            w("  ONE-WAY DELAY (OWD) STATISTICS  [ms]")
            w("-" * 72)
            w(f"  N (valid packets)  : {len(owd_vals)}")
            w(f"  Mean               : {np.mean(owd_vals):.3f} ms")
            w(f"  Std Dev            : {np.std(owd_vals, ddof=1):.3f} ms")
            w(f"  Minimum            : {np.min(owd_vals):.3f} ms")
            w(f"  Maximum            : {np.max(owd_vals):.3f} ms")
            w(f"  Median (P50)       : {np.percentile(owd_vals, 50):.3f} ms")
            w(f"  P75                : {np.percentile(owd_vals, 75):.3f} ms")
            w(f"  P95                : {np.percentile(owd_vals, 95):.3f} ms")
            w(f"  P99                : {np.percentile(owd_vals, 99):.3f} ms")
            w(f"  P99.9              : {np.percentile(owd_vals, 99.9):.3f} ms")
            w()

            if _SCIPY_AVAILABLE:
                try:
                    pos = owd_vals[owd_vals > 0]
                    if len(pos) > 10:
                        shape, loc, scale = _scipy_stats.lognorm.fit(pos, floc=0)
                        ks_stat, ks_p = _scipy_stats.kstest(pos, 'lognorm', args=(shape, loc, scale))
                        w("-" * 72)
                        w("  DISTRIBUTION FIT -- Log-Normal  (OWD > 0 ms)")
                        w("-" * 72)
                        w(f"  Shape (sigma)      : {shape:.4f}")
                        w(f"  Scale (exp(mu))    : {scale:.4f} ms")
                        w(f"  KS statistic       : {ks_stat:.4f}")
                        w(f"  KS p-value         : {ks_p:.4f}  "
                          f"({'good fit' if ks_p > 0.05 else 'poor fit -- consider Weibull'})")
                        w()
                except Exception:
                    pass

        w("-" * 72)
        w("  DELAY BUDGET INTERPRETATION")
        w("-" * 72)
        w("  Expected delay components:")
        w("    - Firmware buffer accumulation  : 0 - 250 ms  (25 samples @ 100 SPS)")
        w("    - ZeroTier P2P tunnel           : 5 - 50 ms   (typical LAN punch-through)")
        w("    - ZeroTier relay (DERP)         : 30 - 200 ms (if direct path blocked)")
        w("    - OS receive queue jitter       : 0 - 10 ms")
        w("    - NTP clock offset bias         : varies (check w32tm /query /status)")
        w()

        if len(owd_vals) >= 2:
            mean_owd = np.mean(owd_vals)
            if mean_owd < 50:
                w("  ASSESSMENT: Excellent -- mean OWD < 50 ms. Likely ZeroTier P2P path.")
            elif mean_owd < 150:
                w("  ASSESSMENT: Good -- mean OWD 50-150 ms. ZeroTier relay may be active.")
            elif mean_owd < 350:
                w("  ASSESSMENT: Moderate -- mean OWD 150-350 ms. Includes firmware buffering.")
            else:
                w("  ASSESSMENT: High latency. Investigate NTP clock sync and ZeroTier path.")
        w()
        w("-" * 72)
        w("  CLOCK SYNC NOTE")
        w("-" * 72)
        w("  OWD = t_receive(PC) - packet_timestamp(RPi).")
        w("  Clock offset between PC and RPi introduces a constant bias in all OWD values.")
        w("  Run clock_offset_probe.py for an NTP-independent offset estimate.")
        w()
        w("=" * 72)

    print(f"  Report saved -> {filepath}")


